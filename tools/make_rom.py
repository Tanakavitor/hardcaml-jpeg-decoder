#!/usr/bin/env python3
"""Put a JPEG into the FPGA design.

usage: python3 tools/make_rom.py picture.jpg [--out-dir quartus]

Writes, in the Quartus project folder:
  jpeg_rom.hex       the JPEG bytes, loaded into on-chip ROM at compile time ($readmemh)
  jpeg_expected.vh   the checksum the decoded image must have (LEDR[1] = match)
Then recompile the Quartus project and program the board.
The JPEG must be baseline (not progressive) and at most 128 KiB.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import jpeg_ref  # noqa: E402

ROM_BYTES = 1 << 17   # must match ADDR_BITS in de10_standard_top.v / rom_addr_bits in system.ml
FB_W, FB_H = 320, 240


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("jpeg")
    ap.add_argument("--out-dir", default=os.path.join(here, "..", "quartus"))
    args = ap.parse_args()

    with open(args.jpeg, "rb") as f:
        data = f.read()
    if len(data) > ROM_BYTES:
        sys.exit("%s is %d bytes; the ROM holds %d. Re-save it smaller (lower quality / size)."
                 % (args.jpeg, len(data), ROM_BYTES))
    try:
        w, h, nf, rgb = jpeg_ref.decode(data)
    except jpeg_ref.DecodeError as e:
        sys.exit("%s cannot be decoded by the FPGA: %s\n"
                 "Re-save it as a baseline JPEG, e.g.\n"
                 "  magick in.jpg -resize 320x240 -interlace none -sampling-factor 4:2:0 -quality 90 out.jpg"
                 % (args.jpeg, e))
    cs = jpeg_ref.checksum(w, h, rgb)

    hex_path = os.path.join(args.out_dir, "jpeg_rom.hex")
    with open(hex_path, "w") as f:
        for b in data:
            f.write("%02x\n" % b)
        f.write("00\n" * (ROM_BYTES - len(data)))
    vh_path = os.path.join(args.out_dir, "jpeg_expected.vh")
    with open(vh_path, "w") as f:
        f.write("// generated by tools/make_rom.py from %s\n" % os.path.basename(args.jpeg))
        f.write("// %dx%d %s, %d bytes\n" % (w, h, "YCbCr" if nf == 3 else "grayscale", len(data)))
        f.write("localparam [31:0] EXPECTED_CHECKSUM = 32'h%08X;\n" % cs)
        f.write("localparam        EXPECTED_VALID    = 1'b1;\n")

    print("%s: %dx%d %s, %d bytes, expected checksum %08X"
          % (args.jpeg, w, h, "YCbCr" if nf == 3 else "grayscale", len(data), cs))
    print("wrote %s and %s" % (hex_path, vh_path))
    if w > FB_W or h > FB_H:
        print("note: only the top-left %dx%d pixels are shown on VGA; the whole image is still "
              "decoded and checksummed." % (FB_W, FB_H))


if __name__ == "__main__":
    main()
